#!/bin/bash

# ThorVG Universal Build Script for macOS
# Builds a fat libthorvg-1.a (arm64 + x86_64) so the extension links once
# with arch=universal and ships as a single .framework covering all Macs.
#
# Runs two meson builds -- the host arch natively, the other cross-compiled
# with -arch flags via a generated meson cross-file (plain clang works: the
# macOS SDK is universal) -- then lipo's both into thirdparty/thorvg/
# builddir/src/libthorvg-1.a, the path SConstruct reads for macOS builds.
#
# Host requirements: macOS with Xcode/CLT, meson, ninja, python3.
# Works on Apple Silicon and Intel hosts alike.

set -e

echo "========================================"
echo "Building ThorVG (Universal: arm64 + x86_64)"
echo "Platform: $(uname -s) $(uname -m)"
echo "Target: Lottie animations only"
echo "========================================"
echo

if [ "$(uname -s)" != "Darwin" ]; then
    echo "ERROR: Universal macOS builds require a macOS host."
    echo "       Current host: $(uname -s)"
    exit 1
fi

if ! command -v meson &> /dev/null; then
    echo "ERROR: meson not found. Install with: brew install meson ninja"
    exit 1
fi

if ! command -v ninja &> /dev/null; then
    echo "ERROR: ninja not found. Install with: brew install ninja"
    exit 1
fi

if ! command -v lipo &> /dev/null; then
    echo "ERROR: lipo not found. Install Xcode Command Line Tools."
    exit 1
fi

CORES=$(sysctl -n hw.ncpu)
echo "Detected $CORES CPU cores for parallel compilation"
echo

cd thirdparty/thorvg

# Apply upstream patches (from Godot's vendored thorvg) on a clean checkout.
# The submodule is pinned to a tag, so patches live in the parent repo and are
# applied here instead of being committed into the submodule.
# 0001 removes thorvg's global operator new/delete overrides, which would
# hijack host-process allocations when statically linked.
PATCH_DIR="../thorvg-upstream-patches"
if git apply --check "$PATCH_DIR/0001-let-delete-be-delete.patch" 2>/dev/null; then
    git apply "$PATCH_DIR/0001-let-delete-be-delete.patch"
    echo "Applied thorvg patch: 0001-let-delete-be-delete.patch"
elif ! git diff --quiet -- src/common/tvgCommon.h; then
    echo "thorvg patches already applied"
fi

# Per-slice options mirror build_thorvg.sh:
#   -Dstatic=true     force the bundled lodepng into the archive
#   -Dextra=lottie_exp  drop 'openmp' -- Apple Clang has no omp.h
#   threads: arm64 slice stays false (ARM macOS compat), x86_64 stays true
COMMON_OPTIONS="-Dbuildtype=release -Doptimization=3 -Db_ndebug=true \
-Ddefault_library=static -Dstatic=true -Dsimd=true -Dpartial=true \
-Dengines=sw -Dloaders=lottie,png -Dbindings=capi -Dtests=false \
-Dextra=lottie_exp"

build_slice() {
    local ARCH="$1"           # arm64 / x86_64
    local THREADS="$2"        # true / false
    local CPU_FAMILY="$3"     # aarch64 / x86_64 (meson naming)
    local BUILDDIR_NAME="builddir_macos-$ARCH"

    echo
    echo "=== ThorVG slice: $ARCH (threads=$THREADS) ==="
    rm -rf "$BUILDDIR_NAME"

    if [ "$(uname -m)" = "$ARCH" ]; then
        # Native: the host compiler already targets this arch.
        meson setup "$BUILDDIR_NAME" $COMMON_OPTIONS -Dthreads=$THREADS \
            --backend=ninja
    else
        # Cross: same clang + universal SDK, just -arch flags.
        mkdir -p "$BUILDDIR_NAME"
        cat > "$BUILDDIR_NAME/.cross.ini" <<EOF
# Auto-generated by build_thorvg_macos_universal.sh -- do not edit by hand.
[binaries]
c = 'clang'
cpp = 'clang++'
ar = 'ar'

[built-in options]
c_args = ['-arch', '$ARCH']
cpp_args = ['-arch', '$ARCH']
c_link_args = ['-arch', '$ARCH']
cpp_link_args = ['-arch', '$ARCH']

[host_machine]
system = 'darwin'
cpu_family = '$CPU_FAMILY'
cpu = '$CPU_FAMILY'
endian = 'little'
EOF
        meson setup "$BUILDDIR_NAME" --cross-file "$BUILDDIR_NAME/.cross.ini" \
            $COMMON_OPTIONS -Dthreads=$THREADS --backend=ninja
    fi
    meson compile -C "$BUILDDIR_NAME" -j "$CORES"
}

build_slice arm64  false aarch64
build_slice x86_64 true  x86_64

# Combine into the canonical builddir/ that SConstruct reads for macOS.
mkdir -p builddir/src
rm -f builddir/src/libthorvg-1.a
lipo -create \
    builddir_macos-arm64/src/libthorvg-1.a \
    builddir_macos-x86_64/src/libthorvg-1.a \
    -output builddir/src/libthorvg-1.a

echo
echo "========================================"
echo "ThorVG Universal build completed!"
echo
lipo -info builddir/src/libthorvg-1.a
echo
echo "Output location: thirdparty/thorvg/builddir/src/"
echo "Library file: libthorvg-1.a (universal, arm64 + x86_64)"
echo "========================================"
echo
echo "Next step: Build Godot extension with SCons"
echo "  scons platform=macos target=template_release arch=universal"
